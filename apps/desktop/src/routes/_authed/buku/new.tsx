import { useEffect, useMemo, useState } from 'react';
import { createFileRoute, Link, useNavigate } from '@tanstack/react-router';
import { useTranslation } from 'react-i18next';
import { z } from 'zod';
import { ArrowLeft } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { BukuForm } from '@/features/buku/BukuForm';
import { bukuApi, type Buku } from '@/lib/buku';
import { masterDataApi, type MasterItem } from '@/lib/masterData';
import type { ExistingBook } from '@/lib/katalog';
import { toBukuInput } from '@/features/buku/schema';
import { useToast } from '@/components/ui/toast-manager';
import { formatTauriError } from '@/lib/errors';

const searchSchema = z.object({
  isbn: z.string().optional(),
  judul: z.string().optional(),
  pengarang: z.string().optional(),
  penerbit: z.string().optional(),
  tahun: z.coerce.number().int().optional(),
  harga: z.coerce.number().int().optional(),
  coverPath: z.string().optional(),
  deskripsi: z.string().optional(),
  kategori: z.string().optional(),
  subjects: z.string().optional(),
  language: z.string().optional(),
});

export const Route = createFileRoute('/_authed/buku/new')({
  validateSearch: (s) => searchSchema.parse(s),
  component: NewBukuRoute,
});

function NewBukuRoute() {
  const { t } = useTranslation(['buku', 'common']);
  const navigate = useNavigate();
  const search = Route.useSearch();
  const { showToast } = useToast();
  const [ddc, setDdc] = useState<MasterItem[]>([]);
  const [kategori, setKategori] = useState<MasterItem[]>([]);
  const [bahasa, setBahasa] = useState<MasterItem[]>([]);
  const [existing, setExisting] = useState<ExistingBook[]>([]);
  const [existingReady, setExistingReady] = useState(false);

  useEffect(() => {
    void Promise.all([
      masterDataApi.list('ddc').then(setDdc).catch(() => undefined),
      masterDataApi.list('kategori').then(setKategori).catch(() => undefined),
      masterDataApi.list('bahasa').then(setBahasa).catch(() => undefined),
    ]);
  }, []);

  // Load the current collection so the generator can learn rak/DDC and keep
  // the book code unique.
  useEffect(() => {
    let cancelled = false;
    bukuApi
      .list({ limit: 500, offset: 0 })
      .then((res) => {
        if (cancelled) return;
        setExisting(
          res.items.map((b) => ({
            kodeBuku: b.kodeBuku,
            kodeDdc: b.kodeDdc,
            rak: b.rak,
            kategori: b.kategori,
          })),
        );
      })
      .catch(() => undefined)
      .finally(() => {
        if (!cancelled) setExistingReady(true);
      });
    return () => {
      cancelled = true;
    };
  }, []);

  const subjects = useMemo(
    () =>
      (search.subjects ?? '')
        .split(',')
        .map((s) => s.trim())
        .filter(Boolean),
    [search.subjects],
  );

  // Prepare initial values from ISBN scanner. DDC/rak/kode are generated by
  // BukuForm once the collection + DDC master are ready (see `autoFill`).
  // Memoized so unrelated re-renders (e.g. the collection finishing loading)
  // don't reset the form and wipe what the user typed.
  const initialFromIsbn = useMemo<Partial<Buku> | null>(() => {
    if (!search.isbn) return null;
    return {
      isbn: search.isbn,
      judul: search.judul || '',
      pengarang: search.pengarang || '',
      penerbit: search.penerbit || '',
      tahunTerbit: search.tahun || 0,
      coverPath: search.coverPath || '',
      kategori: search.kategori || '',
      deskripsi: search.deskripsi || '',
      // Generated later:
      kodeBuku: '',
      kodeDdc: '',
      jumlahEksemplar: 1,
      sumber: '',
      harga: search.harga ?? 0,
      bahasa: search.language || '',
      rak: '',
    };
  }, [
    search.isbn,
    search.judul,
    search.pengarang,
    search.penerbit,
    search.tahun,
    search.coverPath,
    search.kategori,
    search.deskripsi,
    search.harga,
    search.language,
  ]);

  return (
    <div className="container mx-auto max-w-3xl xl:max-w-5xl 2xl:max-w-7xl p-6 md:p-8">
      <div className="mb-6 flex items-center justify-between">
        <Button asChild variant="ghost" size="sm">
          <Link to="/buku">
            <ArrowLeft className="mr-2 h-4 w-4" />
            {t('common:actions.back')}
          </Link>
        </Button>
      </div>

      <div className="mb-6">
        <h1 className="text-2xl font-bold tracking-tight">{t('buku:form.newTitle')}</h1>
        <p className="text-sm text-muted-foreground">
          {search.isbn 
            ? `${t('buku:form.newSubtitle')} (dari ISBN: ${search.isbn})`
            : t('buku:form.newSubtitle')
          }
        </p>
      </div>

      <BukuForm
        initial={initialFromIsbn}
        ddcOptions={ddc}
        kategoriOptions={kategori}
        bahasaOptions={bahasa}
        autoFill={{ subjects, existing, ready: existingReady }}
        submitLabel={t('buku:form.submitCreate')}
        onCancel={() => void navigate({ to: '/buku' })}
        onSubmit={async (values) => {
          try {
            await bukuApi.create(toBukuInput(values));
            showToast({ title: t('buku:feedback.createSuccess') });
            void navigate({ to: '/buku' });
          } catch (err) {
            showToast({
              variant: 'destructive',
              title: t('buku:feedback.createError', {
                message: formatTauriError(err),
              }),
            });
          }
        }}
      />
    </div>
  );
}
